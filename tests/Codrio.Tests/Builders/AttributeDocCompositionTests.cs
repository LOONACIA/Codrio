using Xunit;

namespace Codrio.Tests;

public class AttributeDocCompositionTests
{
    [Fact]
    public void BlockNamespace_ComposesAttributesAndDocumentationWithExactOutputAndCompiles()
    {
        var file = CSharp.File().AutoGeneratedHeader().NullableEnable().Using("System")
            .Namespace("Example", ConfigureTypes);
        const string expected = "// <auto-generated/>\n#nullable enable\n\nusing System;\n\n"
            + "namespace Example\n{\n"
            + "    /// <summary>Marks declarations.</summary>\n"
            + "    [System.AttributeUsage(System.AttributeTargets.All, AllowMultiple = true)]\n"
            + "    public sealed class TagAttribute : Attribute\n    {\n    }\n\n"
            + "    /// <summary>Handles changes.</summary>\n"
            + "    /// <param name=\"value\">The new value.</param>\n"
            + "    [Tag]\n    public delegate void ChangedHandler([Tag] int value);\n\n"
            + "    /// <summary>Available colors.</summary>\n    [Flags]\n    [Tag]\n"
            + "    public enum Color\n    {\n"
            + "        /// <summary>Red.</summary>\n        [Tag]\n        Red = 1,\n"
            + "        /// <summary>Green.</summary>\n        [Tag]\n        [Tag]\n        Green = 2\n    }\n\n"
            + "    /// <summary>Reads values.</summary>\n    [Tag]\n    public interface IStore\n    {\n"
            + "        /// <summary>Reads the count.</summary>\n"
            + "        /// <param name=\"caller\">The caller.</param>\n"
            + "        /// <returns>The count.</returns>\n        [Tag]\n        int Read(string caller);\n\n"
            + "        /// <summary>Gets the count.</summary>\n        [Tag]\n        int Count { get; }\n    }\n\n"
            + "    /// <summary>Stores a &lt; b &amp; c.\n    /// Tracks changes.</summary>\n"
            + "    /// <remarks>\n    /// See <see cref=\"IStore\"/> &amp; its members.\n    /// </remarks>\n"
            + "    [Tag]\n    public class Store : IStore\n    {\n"
            + "        /// <summary>The stored count.</summary>\n        [Tag]\n        private int count;\n\n"
            + "        /// <summary>Creates a store.</summary>\n"
            + "        /// <param name=\"count\">The initial count.</param>\n        [Tag]\n"
            + "        public Store([Tag] int count)\n        {\n            this.count = count;\n        }\n\n"
            + "        /// <summary>Reads &lt;count&gt; &amp; reports changes.</summary>\n"
            + "        /// <param name=\"caller\">The caller.</param>\n"
            + "        /// <returns>The stored count.</returns>\n        [Tag]\n        [return: Tag]\n"
            + "        public int Read([System.Runtime.CompilerServices.CallerMemberName] string caller = \"\")\n"
            + "        {\n            Changed?.Invoke(count);\n            return count;\n        }\n\n"
            + "        /// <summary>Gets the count.</summary>\n        [Tag]\n        public int Count\n        {\n"
            + "            get\n            {\n                return count;\n            }\n        }\n\n"
            + "        /// <summary>Reads an entry.</summary>\n"
            + "        /// <param name=\"index\">The offset.</param>\n        [Tag]\n"
            + "        public int this[[Tag] int index] => count + index;\n\n"
            + "        /// <summary>Reports changes.</summary>\n        [Tag]\n"
            + "        public event ChangedHandler? Changed;\n    }\n\n"
            + "    /// <summary>A numeric value.</summary>\n    [Tag]\n    public struct Value\n    {\n"
            + "        /// <summary>Preserves the value.</summary>\n"
            + "        /// <param name=\"value\">The input.</param>\n"
            + "        /// <returns>The input unchanged.</returns>\n        [Tag]\n"
            + "        public static Value operator +([Tag] Value value) => value;\n    }\n\n"
            + "    /// <summary>Stores an entry.</summary>\n"
            + "    /// <param name=\"Count\">The entry count.</param>\n    [Tag]\n"
            + "    public record Entry([Tag] int Count);\n}\n";

        OutputAssert.Equal(expected, file.ToString());
        OutputAssert.Equal(expected, file.ToString());
        CompilationAssert.NoErrors(file.ToString());
    }

    [Fact]
    public void FileScopedNamespace_ComposesTheSameAttributesAndDocumentationAndCompiles()
    {
        var file = CSharp.File().AutoGeneratedHeader().NullableEnable().Using("System")
            .Add(CSharp.FileScopedNamespace("Example", ConfigureTypes));

        CompilationAssert.NoErrors(file.ToString());
    }

    private static void ConfigureTypes(NamespaceBuilder ns)
    {
        var handler = CSharp.Delegate("ChangedHandler", d => d.Public().Attribute("Tag")
            .Parameter("int", "value", p => p.Attribute("Tag"))
            .Doc(doc => doc.Summary("Handles changes.").Param("value", "The new value.")));
        var field = CSharp.Field("int", "count", f => f.Private().Attribute("Tag")
            .Doc(d => d.Summary("The stored count.")));
        var read = CSharp.Method("Read", m => m.Public().Returns("int").Attribute("Tag").Attribute("return: Tag")
            .Parameter("string", "caller", p => p.Attribute("System.Runtime.CompilerServices.CallerMemberName").Default("\"\""))
            .Doc(d => d.Summary("Reads <count> & reports changes.").Param("caller", "The caller.").Returns("The stored count."))
            .Body(b => b.Line("Changed?.Invoke(count);").Line("return count;")));
        var indexer = CSharp.Indexer("int", x => x.Public().Doc(d => d.Summary("Reads an entry.").Param("index", "The offset."))
            .Attribute("Tag").Parameter("int", "index", p => p.Attribute("Tag")).Arrow("count + index"));
        var operatorBuilder = CSharp.Operator("Value", "+", o => o.Public().Static().Attribute("Tag")
            .Parameter("Value", "value", p => p.Attribute("Tag"))
            .Doc(d => d.Summary("Preserves the value.").Param("value", "The input.").Returns("The input unchanged."))
            .Arrow("value"));

        ns.Class("TagAttribute", c => c.Public().Sealed().BaseType("Attribute")
                .Attribute("System.AttributeUsage", "System.AttributeTargets.All", "AllowMultiple = true")
                .Doc(d => d.Summary("Marks declarations.")))
            .Add(handler)
            .Enum("Color", e => e.Public().Attribute("Flags").Attribute("Tag").Doc(d => d.Summary("Available colors."))
                .Member("Red", "1", m => m.Attribute("Tag").Doc(d => d.Summary("Red.")))
                .Member("Green", "2", m => m.Doc(d => d.Summary("Green.")).Attribute("Tag").Attribute("Tag")))
            .Interface("IStore", i => i.Public().Doc(d => d.Summary("Reads values.")).Attribute("Tag")
                .Method("Read", m => m.Returns("int").Parameter("string", "caller").Attribute("Tag")
                    .Doc(d => d.Summary("Reads the count.").Param("caller", "The caller.").Returns("The count.")))
                .Add(CSharp.Property("int", "Count", p => p.Get().Doc(d => d.Summary("Gets the count.")).Attribute("Tag"))))
            .Class("Store", c => c.Public().BaseType("IStore").Attribute("Tag")
                .Doc(d => d.Summary("Stores a < b & c.\r\nTracks changes.")
                    .Xml("<remarks>\r\nSee <see cref=\"IStore\"/> &amp; its members.\n</remarks>"))
                .Add(field)
                .Constructor(k => k.Public().Attribute("Tag").Parameter("int", "count", p => p.Attribute("Tag"))
                    .Doc(d => d.Summary("Creates a store.").Param("count", "The initial count."))
                    .Body(b => b.Line("this.count = count;")))
                .Add(read)
                .Property("int", "Count", p => p.Public().Attribute("Tag").Doc(d => d.Summary("Gets the count."))
                    .Get(a => a.Body(b => b.Line("return count;"))))
                .Add(indexer)
                .Event("ChangedHandler?", "Changed", e => e.Public().Doc(d => d.Summary("Reports changes.")).Attribute("Tag")))
            .Struct("Value", s => s.Public().Attribute("Tag").Doc(d => d.Summary("A numeric value.")).Add(operatorBuilder))
            .Add(CSharp.Record("Entry", r => r.Public().Attribute("Tag")
                .PrimaryParameter("int", "Count", p => p.Attribute("Tag"))
                .Doc(d => d.Summary("Stores an entry.").Param("Count", "The entry count."))));
    }
}
