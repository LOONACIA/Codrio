using System;
using System.ComponentModel;
using System.Runtime.CompilerServices;
using System.Runtime.InteropServices;
using Codrio.Tests.Fixtures;
using Xunit;

namespace Codrio.Tests;

public class TypeOverloadCompositionTests
{
    [Fact]
    public void CompleteFile_ComposesAllTypeOverloadKindsWithExactOutputAndCompiles()
    {
        var handler = CSharp.Delegate("ReadHandler", d => d.Public().Returns(typeof(int))
            .Attribute<DescriptionAttribute>("\"reads\"")
            .Parameter<string>("name", p => p.Attribute(typeof(InAttribute)))
            .Parameter(typeof(int), "offset", p => p.Attribute<InAttribute>()));
        var count = CSharp.Field<int>("count", f => f.Private());
        var indexer = CSharp.Indexer(typeof(int), x => x.Public()
            .Parameter<int>("index", p => p.Attribute<InAttribute>()).Arrow("count + index"));
        var unequal = CSharp.Operator(typeof(bool), "!=", o => o.Public().Static()
            .Parameter("Value", "left").Parameter<int>("right", p => p.Attribute(typeof(InAttribute)))
            .Arrow("!(left == right)"));
        var file = CSharp.File().AutoGeneratedHeader().NullableEnable().Using("System")
            .Namespace("Example", n => n
                .Add(handler)
                .Delegate("TryHandler", d => d.Returns<bool>().Attribute(typeof(DescriptionAttribute), "\"tries\"")
                    .Parameter(typeof(string), "name"))
                .Enum("Access", e => e.Public().UnderlyingType<byte>().Attribute<FlagsAttribute>()
                    .Member("None", "0")
                    .Member("Read", "1", m => m.Attribute(typeof(DescriptionAttribute), "\"read\""))
                    .Member("Write", "2", m => m.Attribute<DescriptionAttribute>("\"write\"")))
                .Interface("IStore", i => i.Public().BaseType<IDisposable>()
                    .Method("Read", m => m.Returns<int>().Parameter(typeof(string), "caller"))
                    .Property<int>("Count", p => p.Get())
                    .Event(typeof(Action), "Changed")
                    .Indexer<int>(x => x.Parameter(typeof(int), "index").Get()))
                .Class("Store", c => c.Public().Attribute(typeof(SerializableAttribute))
                    .BaseType(typeof(Outer<int>.Leaf)).BaseType("IStore")
                    .TypeParameter("T", t => t.Constraint("class").Constraint<IDisposable>()
                        .Constraint(typeof(IComparable<int>)).Constraint("new()"))
                    .Add(count)
                    .Field(typeof(Outer<int>.Inner<string>[,][]), "items", f => f.Private().Initializer("null!"))
                    .Field<int?>("optional", f => f.Private())
                    .Constructor(k => k.Public().Parameter<int>("count", p => p.Attribute(typeof(InAttribute)))
                        .Parameter(typeof(string), "name", p => p.Attribute<InAttribute>())
                        .Body(b => b.Line("this.count = count;")))
                    .Method("Read", m => m.Public().Returns(typeof(int)).Attribute<DescriptionAttribute>("\"reads\"")
                        .Parameter<string>("caller", p => p.Attribute<CallerMemberNameAttribute>().Default("\"\""))
                        .Body(b => b.Line("Changed?.Invoke();").Line("return count;")))
                    .Property(typeof(int), "Count", p => p.Public().Arrow("count"))
                    .Event<Action>("Changed", e => e.Public())
                    .Add(indexer)
                    .Method("Dispose", m => m.Public().Returns(typeof(void)).Body()))
                .Struct("Value", s => s.Public()
                    .Operator<bool>("==", o => o.Public().Static().Parameter("Value", "left")
                        .Parameter(typeof(int), "right", p => p.Attribute<InAttribute>()).Arrow("right == 0"))
                    .Add(unequal)
                    .ImplicitOperator<int>(o => o.Public().Static().Parameter("Value", "value").Arrow("0"))
                    .Add(CSharp.ExplicitOperator(typeof(long), o => o.Public().Static().Parameter("Value", "value").Arrow("0L"))))
                .Add(CSharp.Record("Entry", r => r.Public().PrimaryParameter<int>("Count", p => p.Attribute<InAttribute>())
                    .PrimaryParameter(typeof(string), "Name", p => p.Attribute(typeof(InAttribute))))));

        const string expected = """
            // <auto-generated/>
            #nullable enable

            using System;

            namespace Example
            {
                [global::System.ComponentModel.DescriptionAttribute("reads")]
                public delegate int ReadHandler([global::System.Runtime.InteropServices.InAttribute] string name, [global::System.Runtime.InteropServices.InAttribute] int offset);

                [global::System.ComponentModel.DescriptionAttribute("tries")]
                delegate bool TryHandler(string name);

                [global::System.FlagsAttribute]
                public enum Access : byte
                {
                    None = 0,
                    [global::System.ComponentModel.DescriptionAttribute("read")]
                    Read = 1,
                    [global::System.ComponentModel.DescriptionAttribute("write")]
                    Write = 2
                }

                public interface IStore : global::System.IDisposable
                {
                    int Read(string caller);

                    int Count { get; }

                    event global::System.Action Changed;

                    int this[int index] { get; }
                }

                [global::System.SerializableAttribute]
                public class Store<T> : global::Codrio.Tests.Fixtures.Outer<int>.Leaf, IStore where T : class, global::System.IDisposable, global::System.IComparable<int>, new()
                {
                    private int count;

                    private global::Codrio.Tests.Fixtures.Outer<int>.Inner<string>[,][] items = null!;

                    private global::System.Nullable<int> optional;

                    public Store([global::System.Runtime.InteropServices.InAttribute] int count, [global::System.Runtime.InteropServices.InAttribute] string name)
                    {
                        this.count = count;
                    }

                    [global::System.ComponentModel.DescriptionAttribute("reads")]
                    public int Read([global::System.Runtime.CompilerServices.CallerMemberNameAttribute] string caller = "")
                    {
                        Changed?.Invoke();
                        return count;
                    }

                    public int Count => count;

                    public event global::System.Action Changed;

                    public int this[[global::System.Runtime.InteropServices.InAttribute] int index] => count + index;

                    public void Dispose()
                    {
                    }
                }

                public struct Value
                {
                    public static bool operator ==(Value left, [global::System.Runtime.InteropServices.InAttribute] int right) => right == 0;

                    public static bool operator !=(Value left, [global::System.Runtime.InteropServices.InAttribute] int right) => !(left == right);

                    public static implicit operator int(Value value) => 0;

                    public static explicit operator long(Value value) => 0L;
                }

                public record Entry([global::System.Runtime.InteropServices.InAttribute] int Count, [global::System.Runtime.InteropServices.InAttribute] string Name);
            }
            """;

        var source = file.ToString();
        OutputAssert.Equal(expected + "\n", source);
        CompilationAssert.NoErrors(source + "\n" + TypeFixtures.Source);
    }
}
