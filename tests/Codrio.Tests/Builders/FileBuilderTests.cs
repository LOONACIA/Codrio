using System;
using Xunit;

namespace Codrio.Tests;

public class FileBuilderTests
{
    [Fact]
    public void FileScopedNamespace_RendersEmptyDeclaration()
    {
        OutputAssert.Equal("namespace A;\n", CSharp.File().FileScopedNamespace("A").ToString());
    }

    [Fact]
    public void FileScopedNamespace_InvokesConfigureImmediatelyAndRendersClasses()
    {
        NamespaceBuilder? configured = null;
        var calls = 0;
        var file = CSharp.File().FileScopedNamespace("A", n =>
        {
            configured = n;
            calls++;
            n.Class("B").Class("C");
        });

        Assert.NotNull(configured);
        Assert.Equal(1, calls);
        OutputAssert.Equal("namespace A;\n\nclass B\n{\n}\n\nclass C\n{\n}\n", file.ToString());
        Assert.Equal(1, calls);
        CompilationAssert.NoErrors(file.ToString());
    }

    [Fact]
    public void FileScopedNamespace_FollowedByFileLevelClassRendersAndCompiles()
    {
        var output = CSharp.File().FileScopedNamespace("A").Class("B").ToString();

        OutputAssert.Equal("namespace A;\n\nclass B\n{\n}\n", output);
        CompilationAssert.NoErrors(output);
    }

    [Fact]
    public void AddFileScopedNamespace_RendersSuppliedInstanceAndLaterChanges()
    {
        var builder = CSharp.FileScopedNamespace("A", n => n.Add(CSharp.Class("B")));
        var file = CSharp.File().Add(builder);

        OutputAssert.Equal("namespace A;\n\nclass B\n{\n}\n", file.ToString());
        builder.Add(CSharp.Class("C"));
        OutputAssert.Equal("namespace A;\n\nclass B\n{\n}\n\nclass C\n{\n}\n", file.ToString());
        CompilationAssert.NoErrors(file.ToString());
    }

    [Fact]
    public void FileScopedNamespaceMethods_ReturnSameFileBuilder()
    {
        var file = CSharp.File();

        Assert.Same(file, file.FileScopedNamespace("A"));
        Assert.Same(file, file.FileScopedNamespace("B", _ => { }));
        Assert.Same(file, file.Add(CSharp.FileScopedNamespace("C")));
    }

    [Fact]
    public void FileScopedNamespaceNullArguments_ThrowWithParameterNameWithoutAddingItems()
    {
        var file = CSharp.File();
        var configured = false;

        Assert.Throws<ArgumentNullException>("name", () => file.FileScopedNamespace(null!));
        Assert.Throws<ArgumentNullException>("name", () => file.FileScopedNamespace(null!, _ => configured = true));
        Assert.Throws<ArgumentNullException>("configure", () => file.FileScopedNamespace("A", null!));
        Assert.False(configured);
        OutputAssert.Equal("", file.ToString());
    }

    [Fact]
    public void FileScopedNamespaces_PreserveOrderWithoutValidatingPlacementOrMixedForms()
    {
        var file = CSharp.File().Class("Before").FileScopedNamespace("A", n => n.Class("B"))
            .Namespace("C", n => n.Class("D")).FileScopedNamespace("E").Raw("// last");

        OutputAssert.Equal("class Before\n{\n}\n\nnamespace A;\n\nclass B\n{\n}\n\nnamespace C\n{\n    class D\n    {\n    }\n}\n\nnamespace E;\n\n// last\n", file.ToString());
    }

    [Theory]
    [InlineData(false)]
    [InlineData(true)]
    public void CompleteFileWithFileScopedNamespace_RendersExpectedSourceAndCompiles(bool configureNamespace)
    {
        var file = CSharp.File().AutoGeneratedHeader().NullableEnable().Using("System");
        if (configureNamespace)
        {
            file.FileScopedNamespace("A", n => n.Class("B"));
        }
        else
        {
            file.FileScopedNamespace("A").Class("B");
        }

        file.Raw("// raw");
        const string expected = "// <auto-generated/>\n#nullable enable\n\nusing System;\n\nnamespace A;\n\nclass B\n{\n}\n\n// raw\n";

        var output = file.ToString();
        OutputAssert.Equal(expected, output);
        OutputAssert.Equal(expected, file.ToString());
        CompilationAssert.NoErrors(output);
    }

    [Fact]
    public void EmptyFile_RendersEmptyString()
    {
        OutputAssert.Equal("", CSharp.File().ToString());
    }

    [Fact]
    public void AutoGeneratedHeader_RendersHeaderOnly()
    {
        OutputAssert.Equal("// <auto-generated/>\n", CSharp.File().AutoGeneratedHeader().ToString());
    }

    [Fact]
    public void NullableEnable_RendersDirectiveOnly()
    {
        OutputAssert.Equal("#nullable enable\n", CSharp.File().NullableEnable().ToString());
    }

    [Theory]
    [InlineData(false)]
    [InlineData(true)]
    public void Headers_RenderInFixedOrder(bool reverse)
    {
        var file = CSharp.File();
        if (reverse)
        {
            file.NullableEnable().AutoGeneratedHeader();
        }
        else
        {
            file.AutoGeneratedHeader().NullableEnable();
        }

        OutputAssert.Equal("// <auto-generated/>\n#nullable enable\n", file.ToString());
    }

    [Fact]
    public void Headers_IgnoreRepeatedCalls()
    {
        var file = CSharp.File().NullableEnable().NullableEnable()
            .AutoGeneratedHeader().AutoGeneratedHeader().NullableEnable();

        OutputAssert.Equal("// <auto-generated/>\n#nullable enable\n", file.ToString());
    }

    [Theory]
    [InlineData(false, false, false, "")]
    [InlineData(true, false, false, "// <auto-generated/>\n")]
    [InlineData(false, true, false, "using System;\n")]
    [InlineData(false, false, true, "class Foo\n{\n}\n")]
    [InlineData(true, true, false, "// <auto-generated/>\n\nusing System;\n")]
    [InlineData(true, false, true, "// <auto-generated/>\n\nclass Foo\n{\n}\n")]
    [InlineData(false, true, true, "using System;\n\nclass Foo\n{\n}\n")]
    [InlineData(true, true, true, "// <auto-generated/>\n\nusing System;\n\nclass Foo\n{\n}\n")]
    public void Sections_SeparateOnlyNonemptySections(bool header, bool usingDirective, bool item, string expected)
    {
        var file = CSharp.File();
        if (item)
        {
            file.Class("Foo");
        }

        if (usingDirective)
        {
            file.Using("System");
        }

        if (header)
        {
            file.AutoGeneratedHeader();
        }

        OutputAssert.Equal(expected, file.ToString());
    }

    [Fact]
    public void NullableEnable_SeparatesFollowingItems()
    {
        var file = CSharp.File().NullableEnable().Class("Foo");

        OutputAssert.Equal("#nullable enable\n\nclass Foo\n{\n}\n", file.ToString());
    }

    [Fact]
    public void Using_PreservesOrderAndDuplicates()
    {
        var file = CSharp.File().Using("System.Text").Using("System").Using("System.Text");

        OutputAssert.Equal("using System.Text;\nusing System;\nusing System.Text;\n", file.ToString());
    }

    [Theory]
    [InlineData("")]
    [InlineData("not a namespace!")]
    [InlineData("static System.Math")]
    [InlineData("Alias = System.String")]
    public void Using_WritesNameWithoutValidation(string name)
    {
        OutputAssert.Equal("using " + name + ";\n", CSharp.File().Using(name).ToString());
    }

    [Fact]
    public void Class_InvokesConfigureImmediatelyAndAddsTopLevelClass()
    {
        ClassBuilder? configured = null;
        var calls = 0;
        var file = CSharp.File().Class("Foo", c =>
        {
            configured = c;
            calls++;
        }).Class("Bar");

        Assert.NotNull(configured);
        Assert.Equal(1, calls);
        OutputAssert.Equal("class Foo\n{\n}\n", configured.ToString());
        OutputAssert.Equal("class Foo\n{\n}\n\nclass Bar\n{\n}\n", file.ToString());
        Assert.Equal(1, calls);
    }

    [Fact]
    public void Add_KeepsSuppliedInstanceAndRendersClass()
    {
        var classBuilder = CSharp.Class("Foo");
        var file = CSharp.File().Add(classBuilder);

        Assert.Same(classBuilder, Assert.Single(file.items).Target);
        OutputAssert.Equal("class Foo\n{\n}\n", file.ToString());
    }

    [Fact]
    public void File_InvokesConfigureImmediatelyOnReturnedBuilder()
    {
        FileBuilder? configured = null;
        var calls = 0;
        var file = CSharp.File(f =>
        {
            configured = f;
            calls++;
            f.Using("System").Class("Foo");
        });

        Assert.Same(file, configured);
        Assert.Equal(1, calls);
        OutputAssert.Equal("using System;\n\nclass Foo\n{\n}\n", file.ToString());
        Assert.Equal(1, calls);
    }

    [Theory]
    [InlineData("// first\n// second")]
    [InlineData("// first\r\n// second")]
    public void Raw_WritesMultipleLinesAndNormalizesCrLf(string code)
    {
        OutputAssert.Equal("// first\n// second\n", CSharp.File().Raw(code).ToString());
    }

    [Fact]
    public void Raw_PreservesUnvalidatedTextAndBlankLines()
    {
        var file = CSharp.File().Raw("  unvalidated!\r\n\r\nlast");

        OutputAssert.Equal("  unvalidated!\n\nlast\n", file.ToString());
    }

    [Fact]
    public void Items_PreserveClassAddAndRawOrder()
    {
        var file = CSharp.File().Raw("// first").Class("Foo")
            .Raw("// middle").Add(CSharp.Class("Bar", _ => { })).Raw("// last");

        OutputAssert.Equal("// first\n\nclass Foo\n{\n}\n\n// middle\n\nclass Bar\n{\n}\n\n// last\n", file.ToString());
    }

    [Fact]
    public void FluentMethods_ReturnSameFileBuilder()
    {
        var file = CSharp.File();

        Assert.Same(file, file.AutoGeneratedHeader());
        Assert.Same(file, file.NullableEnable());
        Assert.Same(file, file.Using("System"));
        Assert.Same(file, file.Class("Foo"));
        Assert.Same(file, file.Class("Bar", _ => { }));
        Assert.Same(file, file.Add(CSharp.Class("Baz")));
        Assert.Same(file, file.Raw("// raw"));
    }

    [Theory]
    [InlineData("")]
    [InlineData("1Foo")]
    [InlineData("Foo.Bar")]
    [InlineData("Foo Bar")]
    [InlineData("Foo-Bar")]
    [InlineData("@@Foo")]
    public void Class_RejectsInvalidNameAtCallTime(string name)
    {
        var file = CSharp.File();
        var configured = false;

        Assert.Throws<ArgumentException>("name", () => file.Class(name));
        Assert.Throws<ArgumentException>("name", () => file.Class(name, _ => configured = true));
        Assert.False(configured);
        OutputAssert.Equal("", file.ToString());
    }

    [Fact]
    public void NullArguments_ThrowWithParameterName()
    {
        var file = CSharp.File();

        Assert.Throws<ArgumentNullException>("configure", () => CSharp.File(null!));
        Assert.Throws<ArgumentNullException>("name", () => file.Using(null!));
        Assert.Throws<ArgumentNullException>("name", () => file.Class(null!));
        Assert.Throws<ArgumentNullException>("name", () => file.Class(null!, _ => { }));
        Assert.Throws<ArgumentNullException>("configure", () => file.Class("Foo", null!));
        Assert.Throws<ArgumentNullException>("classBuilder", () => file.Add((ClassBuilder)null!));
        Assert.Throws<ArgumentNullException>("code", () => file.Raw(null!));
        OutputAssert.Equal("", file.ToString());
    }

    [Fact]
    public void CompleteFile_RendersExpectedSourceAndCompiles()
    {
        var file = CSharp.File(f => f.Class("Foo").NullableEnable().Using("System")
            .AutoGeneratedHeader().Add(CSharp.Class("Bar")).Raw("// raw"));
        const string expected = "// <auto-generated/>\n#nullable enable\n\nusing System;\n\nclass Foo\n{\n}\n\nclass Bar\n{\n}\n\n// raw\n";

        var output = file.ToString();
        OutputAssert.Equal(expected, output);
        OutputAssert.Equal(expected, file.ToString());
        CompilationAssert.NoErrors(output);
    }

    [Fact]
    public void Namespace_RendersEmptyBlock()
    {
        OutputAssert.Equal("namespace A\n{\n}\n", CSharp.File().Namespace("A").ToString());
    }

    [Fact]
    public void Namespace_InvokesConfigureImmediatelyAndAddsNamespace()
    {
        NamespaceBuilder? configured = null;
        var calls = 0;
        var file = CSharp.File().Namespace("A.B", n =>
        {
            configured = n;
            calls++;
            n.Class("C").Class("D");
        });

        Assert.NotNull(configured);
        Assert.Equal(1, calls);
        OutputAssert.Equal("namespace A.B\n{\n    class C\n    {\n    }\n\n    class D\n    {\n    }\n}\n", file.ToString());
        Assert.Equal(1, calls);
    }

    [Fact]
    public void AddNamespace_KeepsSuppliedInstanceAndRendersLaterChanges()
    {
        var builder = CSharp.Namespace("A", n => n.Add(CSharp.Class("C")));
        var file = CSharp.File().Add(builder);

        OutputAssert.Equal("namespace A\n{\n    class C\n    {\n    }\n}\n", file.ToString());
        builder.Class("D");
        OutputAssert.Equal("namespace A\n{\n    class C\n    {\n    }\n\n    class D\n    {\n    }\n}\n", file.ToString());
    }

    [Fact]
    public void Items_PreserveClassNamespaceAndRawOrder()
    {
        var file = CSharp.File().Class("Before").Namespace("A", n => n.Class("C"))
            .Raw("// middle").Add(CSharp.Namespace("B")).Class("After");

        OutputAssert.Equal("class Before\n{\n}\n\nnamespace A\n{\n    class C\n    {\n    }\n}\n\n// middle\n\nnamespace B\n{\n}\n\nclass After\n{\n}\n", file.ToString());
        CompilationAssert.NoErrors(file.ToString());
    }

    [Fact]
    public void NamespaceMethods_ReturnSameFileBuilder()
    {
        var file = CSharp.File();

        Assert.Same(file, file.Namespace("A"));
        Assert.Same(file, file.Namespace("B", _ => { }));
        Assert.Same(file, file.Add(CSharp.Namespace("C")));
    }

    [Fact]
    public void NamespaceNullArguments_ThrowWithParameterName()
    {
        var file = CSharp.File();

        Assert.Throws<ArgumentNullException>("name", () => file.Namespace(null!));
        Assert.Throws<ArgumentNullException>("name", () => file.Namespace(null!, _ => { }));
        Assert.Throws<ArgumentNullException>("configure", () => file.Namespace("A", null!));
        Assert.Throws<ArgumentNullException>("namespaceBuilder", () => file.Add((NamespaceBuilder)null!));
        OutputAssert.Equal("", file.ToString());
    }

    [Fact]
    public void CompleteFileWithNamespaces_RendersExpectedSourceAndCompiles()
    {
        var file = CSharp.File(f => f.Namespace("A.B", n => n.Class("C"))
            .NullableEnable().Using("System").AutoGeneratedHeader()
            .Add(CSharp.Namespace("D", n => n.Add(CSharp.Class("class"))))
            .Class("TopLevel"));
        const string expected = "// <auto-generated/>\n#nullable enable\n\nusing System;\n\nnamespace A.B\n{\n    class C\n    {\n    }\n}\n\nnamespace D\n{\n    class @class\n    {\n    }\n}\n\nclass TopLevel\n{\n}\n";

        var output = file.ToString();
        OutputAssert.Equal(expected, output);
        OutputAssert.Equal(expected, file.ToString());
        CompilationAssert.NoErrors(output);
    }

    [Fact]
    public void KeywordClassName_IsEscapedAndCompiles()
    {
        var output = CSharp.File().Class("class").ToString();

        OutputAssert.Equal("class @class\n{\n}\n", output);
        CompilationAssert.NoErrors(output);
    }
}
