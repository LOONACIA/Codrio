using Xunit;

namespace Codrio.Tests;

public class MemberCompositionTests
{
    [Fact]
    public void BlockNamespace_ComposesMembersWithExactOutputAndCompiles()
    {
        var file = CSharp.File().AutoGeneratedHeader().NullableEnable().Using("System.Threading.Tasks")
            .Namespace("Example", ConfigureTypes);
        const string expected = "// <auto-generated/>\n#nullable enable\n\nusing System.Threading.Tasks;\n\n" +
            "namespace Example\n{\n" +
            "    public interface IStore\n    {\n" +
            "        T Echo<T>(T value) where T : class;\n\n" +
            "        bool TryGet(out int value);\n    }\n\n" +
            "    public abstract class StoreBase\n    {\n" +
            "        public abstract int Read(int fallback);\n\n" +
            "        public virtual string Label() => \"base\";\n    }\n\n" +
            "    public sealed class Store : StoreBase, IStore\n    {\n" +
            "        public const int Limit = 10;\n\n" +
            "        private static readonly int DefaultValue;\n\n" +
            "        private readonly int value;\n\n" +
            "        static Store()\n        {\n            DefaultValue = 1;\n        }\n\n" +
            "        public Store()\n        {\n            value = DefaultValue;\n        }\n\n" +
            "        public Store(int value)\n        {\n            this.value = value;\n        }\n\n" +
            "        public override int Read(int fallback)\n        {\n" +
            "            if (value > 0)\n            {\n" +
            "                if (value <= Limit)\n                {\n                    return value;\n                }\n" +
            "                else\n                {\n                    return Limit;\n                }\n" +
            "            }\n            else\n            {\n                return fallback;\n            }\n        }\n\n" +
            "        public override string Label() => \"store\";\n\n" +
            "        public bool TryGet(out int result)\n        {\n            result = value;\n            return true;\n        }\n\n" +
            "        public async Task<int> ReadAsync()\n        {\n            await Task.Yield();\n            return value;\n        }\n\n" +
            "        public T Echo<T>(T item) where T : class => item;\n    }\n\n" +
            "    public struct Counter\n    {\n        private int value;\n\n" +
            "        public Counter(int value)\n        {\n            this.value = value;\n        }\n\n" +
            "        public readonly int Read() => value;\n    }\n\n" +
            "    public record Entry\n    {\n        private readonly int value;\n\n" +
            "        public Entry(int value)\n        {\n            this.value = value;\n        }\n\n" +
            "        public int Read() => value;\n    }\n\n" +
            "    public static class StoreExtensions\n    {\n" +
            "        public static int ReadOrZero(this Store store) => store.Read(0);\n    }\n}\n";

        OutputAssert.Equal(expected, file.ToString());
        OutputAssert.Equal(expected, file.ToString());
        CompilationAssert.NoErrors(file.ToString());
    }

    [Fact]
    public void FileScopedNamespace_ComposesTheSameMembersAndCompiles()
    {
        var file = CSharp.File().AutoGeneratedHeader().NullableEnable().Using("System.Threading.Tasks")
            .Add(CSharp.FileScopedNamespace("Example", ConfigureTypes));

        CompilationAssert.NoErrors(file.ToString());
    }

    private static void ConfigureTypes(NamespaceBuilder ns)
    {
        ns.Interface("IStore", i => i.Public()
                .Method("Echo", m => m.Returns("T").TypeParameter("T", t => t.Constraint("class"))
                    .Parameter("T", "value"))
                .Add(CSharp.Method("TryGet").Returns("bool").Parameter("int", "value", p => p.Out())))
            .Class("StoreBase", c => c.Public().Abstract()
                .Method("Read", m => m.Public().Abstract().Returns("int").Parameter("int", "fallback"))
                .Add(CSharp.Method("Label").Public().Virtual().Returns("string").Arrow("\"base\"")))
            .Class("Store", c => c.Public().Sealed().BaseType("StoreBase").BaseType("IStore")
                .Field("int", "Limit", f => f.Public().Const().Initializer("10"))
                .Add(CSharp.Field("int", "DefaultValue").Private().Static().ReadOnly())
                .Field("int", "value", f => f.Private().ReadOnly())
                .Constructor(k => k.Static().Body(b => b.Line("DefaultValue = 1;")))
                .Add(CSharp.Constructor().Public().Body(b => b.Line("value = DefaultValue;")))
                .Constructor(k => k.Public().Parameter("int", "value").Body(b => b.Line("this.value = value;")))
                .Method("Read", m => m.Public().Override().Returns("int").Parameter("int", "fallback")
                    .Body(b => b.Block("if (value > 0)", positive => positive
                            .Block("if (value <= Limit)", within => within.Line("return value;"))
                            .Block("else", above => above.Line("return Limit;")))
                        .Block("else", otherwise => otherwise.Line("return fallback;"))))
                .Add(CSharp.Method("Label").Public().Override().Returns("string").Arrow("\"store\""))
                .Method("TryGet", m => m.Public().Returns("bool").Parameter("int", "result", p => p.Out())
                    .Body(b => b.Line("result = value;").Line("return true;")))
                .Add(CSharp.Method("ReadAsync").Public().Async().Returns("Task<int>")
                    .Body(b => b.Line("await Task.Yield();").Line("return value;")))
                .Method("Echo", m => m.Public().Returns("T").TypeParameter("T", t => t.Constraint("class"))
                    .Parameter("T", "item").Arrow("item")))
            .Struct("Counter", s => s.Public().Add(CSharp.Field("int", "value").Private())
                .Add(CSharp.Constructor(k => k.Public().Parameter("int", "value")
                    .Body(b => b.Line("this.value = value;"))))
                .Method("Read", m => m.Public().ReadOnly().Returns("int").Arrow("value")))
            .Record("Entry", r => r.Public().Field("int", "value", f => f.Private().ReadOnly())
                .Constructor(k => k.Public().Parameter("int", "value").Body(b => b.Line("this.value = value;")))
                .Add(CSharp.Method("Read", m => m.Public().Returns("int").Arrow("value"))))
            .Class("StoreExtensions", c => c.Public().Static()
                .Method("ReadOrZero", m => m.Public().Static().Returns("int")
                    .Parameter("Store", "store", p => p.This()).Arrow("store.Read(0)")));
    }
}
