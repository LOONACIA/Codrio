using Xunit;

namespace Codrio.Tests;

public class TypeBuilderCompositionTests
{
    [Fact]
    public void BlockNamespace_ComposesAllTypeKindsWithExactOutputAndCompiles()
    {
        var file = CSharp.File().AutoGeneratedHeader().NullableEnable().Using("System")
            .Namespace("Example", ConfigureTypes);
        const string expected = "// <auto-generated/>\n#nullable enable\n\nusing System;\n\n"
            + "namespace Example\n{\n"
            + "    public interface IMarker\n    {\n    }\n\n"
            + "    public interface IValue<T> : IMarker where T : class\n    {\n    }\n\n"
            + "    public abstract class Base\n    {\n    }\n\n"
            + "    public sealed partial class Container<T>(T value) : Base, IValue<T> where T : class, new()\n    {\n"
            + "        // Container body\n\n"
            + "        public static class LevelOne\n        {\n"
            + "            internal enum LevelTwo : byte\n            {\n                First,\n                Second = 2\n            }\n"
            + "        }\n    }\n\n"
            + "    public readonly partial struct Buffer<T>(int count = 0) : IMarker where T : struct\n    {\n"
            + "        // Buffer body\n    }\n\n"
            + "    internal struct EmptyValue\n    {\n    }\n\n"
            + "    public abstract record Entity;\n\n"
            + "    public sealed record Data<T>(T Value) : Entity, IMarker where T : class;\n\n"
            + "    public readonly record struct Point(int X, int Y = 0) : IMarker;\n\n"
            + "    internal record struct Token(int Value);\n\n"
            + "    public enum Color : byte\n    {\n        Red = 1,\n        Green = 1 << 2,\n        Blue = Red | Green\n    }\n\n"
            + "    internal enum Mode\n    {\n        @class,\n        Active\n    }\n}\n";

        OutputAssert.Equal(expected, file.ToString());
        OutputAssert.Equal(expected, file.ToString());
        CompilationAssert.NoErrors(file.ToString());
    }

    [Fact]
    public void FileScopedNamespace_ComposesTheSameTypesAndCompiles()
    {
        var file = CSharp.File().AutoGeneratedHeader().NullableEnable().Using("System")
            .Add(CSharp.FileScopedNamespace("Example", ConfigureTypes));

        CompilationAssert.NoErrors(file.ToString());
    }

    private static void ConfigureTypes(NamespaceBuilder ns)
    {
        ns.Interface("IMarker", i => i.Public())
            .Add(CSharp.Interface("IValue", i => i.Public().BaseType("IMarker")
                .TypeParameter("T", t => t.Constraint("class"))))
            .Class("Base", c => c.Public().Abstract())
            .Add(CSharp.Class("Container", c => c.Partial().Sealed().Public()
                .TypeParameter("T", t => t.Constraint("class").Constraint("new()"))
                .PrimaryParameter("T", "value").BaseType("Base").BaseType("IValue<T>")
                .Raw("// Container body")
                .Class("LevelOne", inner => inner.Static().Public()
                    .Add(CSharp.Enum("LevelTwo", e => e.Internal().UnderlyingType("byte")
                        .Member("First").Member("Second", "2"))))))
            .Struct("Buffer", s => s.Partial().ReadOnly().Public().BaseType("IMarker")
                .TypeParameter("T", t => t.Constraint("struct"))
                .PrimaryParameter("int", "count", p => p.Default("0")).Raw("// Buffer body"))
            .Add(CSharp.Struct("EmptyValue").Internal())
            .Record("Entity", r => r.Public().Abstract())
            .Add(CSharp.Record("Data", r => r.Public().Sealed()
                .TypeParameter("T", t => t.Constraint("class")).PrimaryParameter("T", "Value")
                .BaseType("Entity").BaseType("IMarker")))
            .RecordStruct("Point", r => r.ReadOnly().Public().PrimaryParameter("int", "X")
                .PrimaryParameter("int", "Y", p => p.Default("0")).BaseType("IMarker"))
            .Add(CSharp.RecordStruct("Token").Internal().PrimaryParameter("int", "Value"))
            .Enum("Color", e => e.Public().UnderlyingType("byte").Member("Red", "1")
                .Member("Green", "1 << 2").Member("Blue", "Red | Green"))
            .Add(CSharp.Enum("Mode").Internal().Member("class").Member("Active"));
    }
}
